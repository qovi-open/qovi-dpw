// chaque paquet. Une licence non reconnue est marquee « A VERIFIER ».
// Usage (dans dpw/qfa_dpw, apres flutter pub get) : dart run tool/third_party.dart
import 'dart:convert';
import 'dart:io';

String classify(String t) {
  final s = t.replaceAll(RegExp(r'\s+'), ' ');
  if (s.contains('Apache License') && s.contains('Version 2.0')) return 'Apache-2.0';
  if (s.contains('Mozilla Public License')) return 'MPL-2.0';
  if (s.contains('GNU GENERAL PUBLIC LICENSE') || s.contains('GNU General Public License')) return 'GPL';
  if (s.contains('Permission is hereby granted, free of charge')) return 'MIT';
  if (s.contains('Redistribution and use in source and binary forms')) {
    return s.contains('Neither the name') || s.contains('may be used to endorse') ? 'BSD-3-Clause' : 'BSD-2-Clause';
  }
  if (s.contains('Permission to use, copy, modify, and/or distribute')) return 'ISC';
  return 'A VERIFIER';
}

void main() {
  final lock = File('pubspec.lock').readAsStringSync();
  final kind = <String, String>{};
  final ver = <String, String>{};
  String? cur;
  for (final l in const LineSplitter().convert(lock)) {
    final m = RegExp(r'^  ([a-z0-9_]+):\s*$').firstMatch(l);
    if (m != null) {
      cur = m.group(1);
      continue;
    }
    if (cur == null) continue;
    final d = RegExp(r'^    dependency: "(.+)"').firstMatch(l);
    if (d != null) kind[cur] = d.group(1)!;
    final v = RegExp(r'^    version: "(.+)"').firstMatch(l);
    if (v != null) ver[cur] = v.group(1)!;
  }
  final cfg = jsonDecode(File('.dart_tool/package_config.json').readAsStringSync()) as Map;
  final base = Directory('.dart_tool').absolute.uri;
  final rows = <String>[];
  for (final p in (cfg['packages'] as List).cast<Map>()) {
    final name = p['name'] as String;
    final k = kind[name];
    if (k == null || k == 'direct dev') continue;
    var dir = base.resolve(p['rootUri'] as String).toFilePath();
    if (dir.endsWith('/')) dir = dir.substring(0, dir.length - 1);
    var lic = 'A VERIFIER';
    for (final f in const ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'COPYING']) {
      final file = File('$dir/$f');
      if (file.existsSync()) {
        lic = classify(file.readAsStringSync());
        break;
      }
    }
    if (name == 'fid_cmp') lic = 'GPL-3.0-or-later (Marc Gandar, fourni avec ces sources)';
    final src = k == 'direct main' || k == 'transitive' ? 'https://pub.dev/packages/$name' : '';
    rows.add('| $name | ${ver[name] ?? ''} | $lic | ${name == 'fid_cmp' ? 'shared/fid_cmp/fid_cmp' : src} |');
  }
  rows.sort();
  final out = StringBuffer()
    ..writeln('# Third-party components — Qovi DpW')
    ..writeln()
    ..writeln('Generated by `dart run tool/third_party.dart` from `pubspec.lock` '
        '(runtime dependencies only). Each licence is read from the LICENSE file of the package.')
    ..writeln()
    ..writeln('| Package | Version | Licence | Source |')
    ..writeln('|---|---|---|---|')
    ..writeln(rows.join('\n'))
    ..writeln()
    ..writeln('Also included in every build:')
    ..writeln()
    ..writeln('| Component | Licence | Source |')
    ..writeln('|---|---|---|')
    ..writeln('| Flutter engine and framework | BSD-3-Clause | https://github.com/flutter/flutter |')
    ..writeln('| Dart SDK | BSD-3-Clause | https://github.com/dart-lang/sdk |')
    ..writeln('| Material Icons font | Apache-2.0 | https://github.com/google/material-design-icons |')
    ..writeln('| zxing-cpp (inside flutter_zxing) | Apache-2.0 | https://github.com/zxing-cpp/zxing-cpp |')
    ..writeln()
    ..writeln('The full licence texts of all components are also shown by the app build in '
        '`data/flutter_assets/NOTICES.Z`.');
  File('THIRD_PARTY_LICENSES.md').writeAsStringSync(out.toString());
  final todo = rows.where((r) => r.contains('A VERIFIER')).length;
  stdout.writeln('THIRD_PARTY_LICENSES.md : ${rows.length} paquets, $todo a verifier');
}
